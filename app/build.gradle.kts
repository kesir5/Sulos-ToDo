// Signing: a stable keystore is required so the SHA-1 registered in Google Cloud
// (needed for Google Drive sign-in) never changes. In GitHub Actions the keystore is
// decoded from repository secrets; locally the default debug keystore is used.
val ksFile = System.getenv("SIGNING_KEYSTORE_FILE")
val hasSigning = !ksFile.isNullOrBlank() && file(ksFile).exists()

